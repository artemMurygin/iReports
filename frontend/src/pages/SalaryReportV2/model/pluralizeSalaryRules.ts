/** "N зарплатных правил" — та же плюрализация, что и `kernel/pluralizeRules.ts`, но с согласованным
 * прилагательным "зарплатное/зарплатных" (нужно только мета-строке шапки `RuleGroupDetailsPanel`,
 * Pencil `fGbpF`: "Сервис · 4 зарплатных правила · август 2025" — `kernel/pluralizeRules.ts`
 * возвращает только существительное без прилагательного). Числительные 2-4 берут прилагательное в
 * родительном падеже множественного числа ("2 зарплатных правила"), не единственного — стандартное
 * согласование числительное+прилагательное+существительное в русском. */
export function pluralizeSalaryRules(count: number): string {
    const mod10 = count % 10
    const mod100 = count % 100
    if (mod10 === 1 && mod100 !== 11) return `${count} зарплатное правило`
    const word = mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20) ? 'правила' : 'правил'
    return `${count} зарплатных ${word}`
}
