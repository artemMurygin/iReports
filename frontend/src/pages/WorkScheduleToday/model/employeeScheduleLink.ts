/**
 * Куда ведёт тап по сотруднику — что на смене, что не на смене (план, Фаза 9: «Переход с карточки
 * сотрудника на его график»). Минимально достаточный переход — десктопная таблица `/work-schedule`
 * (узел `Cko6w`, вкладка «Календарь», Фаза 6) с двумя query-параметрами:
 * - `employeeId` — `pages/WorkSchedule` подсвечивает и прокручивает к строке этого сотрудника
 *   (`useWorkSchedulePage`'s `highlightedEmployeeId`, читается один раз при монтировании тем же
 *   приёмом, что и `month`/`departmentId` там же);
 * - `month` — месяц выбранного на мобильном экране дня (`YYYY-MM`, первые 7 символов ISO-даты), а
 *   не всегда текущий месяц: неделя ленты (`buildWeekDays`) может пересекать границу месяца (см.
 *   её тест "crosses a month boundary correctly"), и без этого параметра таблица открылась бы на
 *   сегодняшнем месяце, где у сотрудника может не быть видимой строки для той даты, с которой
 *   кликнули.
 *
 * Отдельная страница-таблица, а не мобильный аналог: `A5SbT` не показывает свой собственный
 * график на месяц — единственный источник данных этого экрана (`model/api.ts`) — состав смены
 * ровно одного дня, этого недостаточно для таблицы «сотрудник × дни месяца».
 */
export function buildEmployeeScheduleLink(employeeId: number, date: string): string {
    return `/work-schedule?employeeId=${employeeId}&month=${date.slice(0, 7)}`
}
