// spec: service/accounting#scenario-оплаченность-заказа-определяется-его-статусом-а-не-накопленной-суммой
//
// RoappOrderStatus — справочник, синхронизируемый из конкретного аккаунта
// RemOnline (см. prisma/schema/roapp.prisma), а НЕ enum в коде: `grupName`
// — произвольная строка, задаваемая в самом RemOnline и специфичная для
// аккаунта заказчика. Поэтому список "оплаченных" групп статуса — открытая
// (расширяемая) константа на уровне бэкенда, а не значение в БД/схеме — тот
// же приём, что и SERVICE_FUNNEL_CATEGORY_ID в
// domains/service/modules/sales/infrastructure/sales.repositories.ts.
//
// Список сверен с реальным справочником roapp_order_statuses аккаунта
// iRepair: до этого здесь стояла заглушка ('Готово'/'Оплачен'/'Выполнен'),
// не пересекавшаяся с фактическими значениями grup_name ни на одну строку,
// из-за чего findOrderPayedItems всегда возвращал пустой набор и ВСЕ
// правила OrderPayed молча считались в ноль.
//
// Аккаунт RemOnline позже переключил язык интерфейса на английский, и
// названия групп статусов сменились ('Закрытые успешно' → 'Closed' и т.п.
// 1:1) — тот же класс проблемы повторился (обнаружено при расследовании,
// почему OrderPayed.FloatPercent снова считал 0 для всего отдела, хотя
// SalesFact того же периода находил заказы). Текущие фактические группы
// аккаунта: 'Closed' (было 'Закрытые успешно'), 'Dropped off' (было
// 'Закрытые неуспешно'), 'Done' (было 'Готовые'), 'In progress' (было
// 'В работе'), 'New' (было 'Новые'), 'Pending' (было 'Отложенные'),
// 'Delivery' (было 'Доставка'). Оплаченным считается только 'Closed' —
// заказ доведён до конца и закрыт с деньгами; 'Done' — ремонт сделан, но
// заказ ещё не закрыт, деньги не получены; 'Dropped off' — отказ.
//
// grupName — произвольная строка из конкретного аккаунта RemOnline (см.
// выше), поэтому при подключении другого аккаунта или смене языка
// интерфейса список надо сверять заново (см. roapp_order_statuses).
// Отдельный UI/эндпоинт для управления им — вне скоупа Фазы 8, плоская
// конфигурация здесь осознанно достаточна.
export const PAID_ORDER_STATUS_GROUPS: readonly string[] = ['Closed'];

export function isPaidOrderStatusGroup(
    grupName: string | null | undefined,
): boolean {
    return grupName != null && PAID_ORDER_STATUS_GROUPS.includes(grupName);
}
