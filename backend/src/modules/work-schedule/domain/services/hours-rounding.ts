const HOURS_PRECISION = 10;

// Защитное округление суммы часов до одного знака после запятой. Часы
// смены (ShiftHours) уже валидируются кратными 0,5, а сумма чисел вида
// n * 0,5 в IEEE 754 double всегда точна (0,5 — степень двойки, ошибка
// накопления вроде 0.1 + 0.2 здесь не возникает) — сегодня эта функция,
// строго говоря, ничего не поправляет. Она всё равно нужна как явная
// гарантия инварианта PRD ("Технические ограничения": "итоги в отчётах и
// в таблице должны совпадать до одного знака после запятой") в ОДНОМ
// месте: если шаг валидации часов когда-нибудь ослабят (например, до
// произвольного Float), сумма молча не разъедется на дробные разряды — и
// не придётся искать все места сложения часов заново.
export function roundHours(value: number): number {
    return Math.round(value * HOURS_PRECISION) / HOURS_PRECISION;
}
