-- AlterTable
-- Аддитивная миграция, без потери данных: добавляет два nullable-столбца,
-- ничего не удаляет и не переименовывает. Исправляет кросс-направленческий
-- баг переименования зарплатных схем (см. комментарий у полей serviceName/
-- shopName в prisma/schema/salary.prisma) — раньше единственное поле `name`
-- на строке motivation_schemas было общим между direction=service и
-- direction=shop, и PATCH одного направления молча переименовывал то, что
-- видело другое.
ALTER TABLE "motivation_schemas" ADD COLUMN     "service_name" TEXT,
ADD COLUMN     "shop_name" TEXT;

-- Backfill: у существующих строк оба направления сразу расходятся с текущим
-- общим `name` как отправной точкой (видимое имя не меняется для уже
-- существующих схем в момент миграции), но становятся независимыми для
-- любого последующего PATCH/create с той или другой стороны. `name`
-- (legacy-колонка) не трогаем и не удаляем — она остаётся историческим
-- фолбэком для мапперов на случай гонки/незаполненного значения.
UPDATE "motivation_schemas" SET "service_name" = "name", "shop_name" = "name";
